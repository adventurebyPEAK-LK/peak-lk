function openCategory(name){

    let category = gear.find(x => x.name === name);

    grid.innerHTML = `
    <button class="filter active" onclick="renderGear('all')">
        ← Back
    </button>
    `;

    grid.innerHTML += category.items.map(item => `

    <article class="gear-card">

        <div class="gear-img"
        style="background-image:url('${item.image || category.image}')">
        </div>

        <div class="gear-info">

            <small>${name}</small>

            <h3>${item.name}</h3>

            <div class="gear-bottom">

                <div class="price">

                ${
                    item.rentPrice
                    ? typeof item.rentPrice === "object"
                        ? `
                        <div>
                            <b>Rent (Manual):</b>
                            Rs. ${item.rentPrice.manual.toLocaleString()}
                            <small>/ DAY</small>
                        </div>

                        <div>
                            <b>Rent (Automatic):</b>
                            Rs. ${item.rentPrice.automatic.toLocaleString()}
                            <small>/ DAY</small>
                        </div>
                        `
                        : `
                        <div>
                            <b>Rent:</b>
                            Rs. ${item.rentPrice.toLocaleString()}
                            <small>/ DAY</small>
                        </div>
                        `
                    : ""
                }

                ${
    item.buyType === "size"
    ? `
    <div>
        <b>Buy (30ml):</b>
        Rs. ${item.buyPrice["30ml"].toLocaleString()}
    </div>

    <div>
        <b>Buy (50ml):</b>
        Rs. ${item.buyPrice["50ml"].toLocaleString()}
    </div>
    `
    : typeof item.buyPrice === "object"
    ? `
    <div>
        <b>Buy (Manual):</b>
        Rs. ${item.buyPrice.manual.toLocaleString()}
    </div>

    <div>
        <b>Buy (Automatic):</b>
        Rs. ${item.buyPrice.automatic.toLocaleString()}
    </div>
    `
    : `
    <div>
        <b>Buy:</b>
        Rs. ${item.buyPrice.toLocaleString()}
    </div>
    `
}

                </div>

                ${
                    item.rentPrice
                    ? `
                    <button class="rent-btn"
                    onclick="openBooking(
                        '${item.name}',
                        '${
                            typeof item.rentPrice === "object"
                            ? "Rs. " + item.rentPrice.manual
                            : "Rs. " + item.rentPrice
                        }'
                    )">
                        ↗
                    </button>
                    `
                    : ""
                }

            </div>

        </div>

    </article>

    `).join("");

}




